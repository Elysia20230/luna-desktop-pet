# 用户说的话里出现这些词时，先给一个"接话"式回复（比随机更贴合）
KEYWORD_REPLIES: list[tuple[tuple[str, ...], str, str]] = [
    (("你好", "在吗", "早上好", "晚上好"), "嗯，我在。你终于想起我了？", "微笑"),
    (("谢谢", "谢了", "感谢"), "这种小事不必谢。……不过，算你有礼貌。", "害羞"),
    (("对不起", "抱歉", "我错了"), "知道错了就好。下次别再犯。", "平静"),
    (("喜欢你", "爱你", "好可爱"), "……别说这种话。笨蛋。", "害羞"),
    (("笨蛋", "傻瓜", "讨厌"), "哦？你刚才是想说什么？", "生气"),
    (("累", "困", "好烦"), "累了就去休息。别硬撑给我看。", "温柔"),
    (("吃饭", "饿", "外卖"), "记得按时吃饭。别指望我提醒你第二次。", "温柔"),
    (("代码", "bug", "报错", "程序", "写") , "又在写那些东西？先给我看看。", "思考"),
]


def _fill(line: str, name: str = "") -> str:
    """把台词里的 {name} 换成称呼。没给名字时用「你」，读起来也通顺。"""
    return line.replace("{name}", (name or "你").strip())


def reply(user_text: str, name: str = "") -> tuple[str, str]:
    """
    根据用户这句话，从离线台词里挑一句。返回 (回复正文, 情绪)。
    注意：返回的情绪会被界面用来换立绘，所以要和台词语气一致。

    name: 角色卡里的称呼（"小仓朝日"这种），台词里有 {name} 时会替换掉。
    """
    text = (user_text or "").strip()

    for keywords, line, emo in KEYWORD_REPLIES:
        if any(k in text for k in keywords):
            emo = mood_mod.normalize(emo) or "平静"
            return _fill(line, name), emo

    # 没有命中关键词：按用户语气猜情绪，再取同档台词
    guessed = mood_mod.guess(text)
    pool = OFFLINE_LINES.get(guessed) or OFFLINE_LINES["平静"]
    return _fill(random.choice(pool), name), guessed


def reply_proactive(name: str = "") -> tuple[str, str]:
    """
    没人说话时她自己冒一句。情绪从上面 6 档里挑，语气比日常搭话更随意。
    返回 (台词, 情绪)，情绪同样用来换立绘。
    """
    emo = random.choice(list(PROACTIVE_LINES.keys()))
    line = random.choice(PROACTIVE_LINES[emo])
    return _fill(line, name), (mood_mod.normalize(emo) or "平静")


def reply_screen(name: str = "") -> tuple[str, str]:
    """
    「看看我在干什么」的离线回复。

    返回 (台词, 情绪)。台词刻意说得泛——离线时程序并不知道屏幕上是什么，
    编得太具体反而可疑（详见 SCREEN_LINES 上方注释）。
    """
    emo = random.choice(list(SCREEN_LINES.keys()))
    line = random.choice(SCREEN_LINES[emo])
    return _fill(line, name), (mood_mod.normalize(emo) or "平静")
